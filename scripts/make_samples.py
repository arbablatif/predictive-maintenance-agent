"""Write the synthetic demo files in samples/, with their ground truth.

These are generated, not measured. No CWRU or NASA data goes into the repo. They let --mock,
the tests and the UI run on a fresh clone, and they are labelled synthetic wherever they appear.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import joblib
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pm_agent.bearing_physics import SKF_6205, fault_frequencies  # noqa: E402
from pm_agent.config import MODEL_DIR, SAMPLE_DIR  # noqa: E402
from pm_agent.synth import bearing_signal, engine_history  # noqa: E402

FS, RPM = 12_000, 1750.0


def save_vibration(name: str, x: np.ndarray) -> None:
    np.savetxt(SAMPLE_DIR / name, x, fmt="%.4f")


def main() -> None:
    SAMPLE_DIR.mkdir(exist_ok=True)
    freqs = fault_frequencies(SKF_6205, RPM)
    save_vibration("synthetic_outer_race.csv", bearing_signal(freqs["bpfo"], RPM, FS, seed=1))
    save_vibration("synthetic_healthy.csv", bearing_signal(None, RPM, FS, seed=2))
    # Far from the training rig's speed, so the tools should flag it.
    slow = fault_frequencies(SKF_6205, 900.0)
    save_vibration("synthetic_out_of_range.csv", bearing_signal(slow["bpfi"], 900.0, FS, seed=3))

    profile = joblib.load(MODEL_DIR / "rul_models.joblib").profile
    engine = engine_history(profile, cycles=170, life=200, seed=4)
    np.savetxt(SAMPLE_DIR / "synthetic_engine.txt", engine.to_numpy(), fmt="%.4f")

    truth = {
        "_note": "All files here are synthetic demo data, generated by scripts/make_samples.py.",
        "synthetic_outer_race.csv": {"fs": FS, "rpm": RPM, "expected": "outer_race"},
        "synthetic_healthy.csv": {"fs": FS, "rpm": RPM, "expected": "normal"},
        "synthetic_out_of_range.csv": {"fs": FS, "rpm": 900.0, "expected": "flagged_out_of_range"},
        "synthetic_engine.txt": {"expected": "engine_history"},
    }
    (SAMPLE_DIR / "ground_truth.json").write_text(json.dumps(truth, indent=2), encoding="utf-8")
    print("wrote", len(truth) - 1, "samples")


if __name__ == "__main__":
    main()
